import express from 'express';
import auth, { authStrict } from '../../middlewares/auth';
import validate from '../../middlewares/validate';
import { userValidation, permissionValidation } from '../../validations';
import { userController, permissionController } from '../../controllers';

const router = express.Router();

router
  .route('/')
  .post(auth('manageUsers'), validate(userValidation.createUser), userController.createUser)
  .get(auth('getUsers'), validate(userValidation.getUsers), userController.getUsers);

router
  .route('/:userId')
  .get(auth('getUsers'), validate(userValidation.getUser), userController.getUser)
  .patch(auth('manageUsers'), validate(userValidation.updateUser), userController.updateUser)
  .delete(auth('manageUsers'), validate(userValidation.deleteUser), userController.deleteUser);

router
  .route('/:userId/role')
  .patch(authStrict('manageUsers'), validate(userValidation.setRole), userController.setRole);

router
  .route('/:userId/status')
  .patch(authStrict('manageUsers'), validate(userValidation.setStatus), userController.setStatus);

router
  .route('/:userId/permissions')
  .get(
    auth('getUsers'),
    validate(permissionValidation.getPermissions),
    permissionController.getPermissions
  )
  .put(
    authStrict('manageUsers'),
    validate(permissionValidation.updatePermissions),
    permissionController.updatePermissions
  );

export default router;

